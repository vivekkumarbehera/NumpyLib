#Mixed tuple with different data types
mixed_tuple = (41, "Ashu", 2.2, False, (1, 2, 3))
print("Mixed Tuple:", mixed_tuple)
print("First Element (Integer):", mixed_tuple[0])
print("Second Element (String):", mixed_tuple[1])
print("Third Element (Float):", mixed_tuple[2])
print("Fourth Element (Boolean):", mixed_tuple[3])
print("Fifth Element (Tuple):", mixed_tuple[4])
print("Element from Inner Tuple:", mixed_tuple[4][1])

